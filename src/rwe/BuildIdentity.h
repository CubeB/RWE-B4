#pragma once

#include <string>

namespace rwe
{
    /**
     * Which build of the game this is, as the commit it was made from: forty
     * hex digits, then `-d` if the source differed from that commit when it
     * was compiled, or `unknown` for a build made without git.
     *
     * Two machines only play the same game if they run the same simulation,
     * and a mismatch is not an error anybody sees: it is a desync at tick 1,
     * reported as a fault in the engine. So the lobby compares this and
     * refuses a peer that differs, before there is a game to desync.
     *
     * The commit is the right size of "same". Debug and Release, Linux and
     * Windows, built at the same commit, are meant to agree, and the CI
     * checks they do. A dirty build is only the same as another dirty build of
     * the same commit by luck, which is what a developer testing two of their
     * own machines gets and no more.
     *
     * It is read from a file regenerated by every build
     * (cmake/GenerateBuildId.cmake), not from config.h: that is written once
     * at configure time and goes stale at the next commit.
     */
    const std::string& buildIdentity();

    /** Eight characters of the commit, and `-d` if dirty: what a person is shown. */
    std::string shortBuildIdentity(const std::string& identity);

    /**
     * Whether a peer announcing `theirs` can be played with by `mine`.
     * Equal identities can. A build that does not know what it is (`unknown`,
     * or empty) cannot say it is different, so it is not refused; a peer
     * that says nothing at all is a build from before this existed, and is.
     */
    bool buildsCompatible(const std::string& mine, const std::string& theirs);

    /** Whether text from the wire is plausibly an identity: hex digits and at most a `-d`. */
    bool isPlausibleBuildIdentity(const std::string& text);
}
